func TestVideoCaptionModel(t *testing.T) {
	model := VideoCaption{Id: "5e5ea5c16897e", CreatedAt: "2020-10-15T06:38:00.000+00:00", UpdatedAt: "2020-10-15T06:38:00.000+00:00", VideoId: "5e5ea5c16897e", BucketId: "d5fg5ehg1c168g7c", FileId: "c5fg5emg1c168grr", Name: "English", Language: "eng", Default: true, Embedded: true, TargetDuration: 93, Status: "ready", Error: "Caption is not a proper .srt file (Invalid timestamp delimiter at line 2)", Size: 4096}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result VideoCaption
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.CreatedAt != model.CreatedAt {
		t.Errorf("Expected CreatedAt %v, got %v", model.CreatedAt, result.CreatedAt)
	}
	if result.UpdatedAt != model.UpdatedAt {
		t.Errorf("Expected UpdatedAt %v, got %v", model.UpdatedAt, result.UpdatedAt)
	}
	if result.VideoId != model.VideoId {
		t.Errorf("Expected VideoId %v, got %v", model.VideoId, result.VideoId)
	}
	if result.BucketId != model.BucketId {
		t.Errorf("Expected BucketId %v, got %v", model.BucketId, result.BucketId)
	}
	if result.FileId != model.FileId {
		t.Errorf("Expected FileId %v, got %v", model.FileId, result.FileId)
	}
	if result.Name != model.Name {
		t.Errorf("Expected Name %v, got %v", model.Name, result.Name)
	}
	if result.Language != model.Language {
		t.Errorf("Expected Language %v, got %v", model.Language, result.Language)
	}
	if result.Default != model.Default {
		t.Errorf("Expected Default %v, got %v", model.Default, result.Default)
	}
	if result.Embedded != model.Embedded {
		t.Errorf("Expected Embedded %v, got %v", model.Embedded, result.Embedded)
	}
	if result.TargetDuration != model.TargetDuration {
		t.Errorf("Expected TargetDuration %v, got %v", model.TargetDuration, result.TargetDuration)
	}
	if result.Status != model.Status {
		t.Errorf("Expected Status %v, got %v", model.Status, result.Status)
	}
	if result.Error != model.Error {
		t.Errorf("Expected Error %v, got %v", model.Error, result.Error)
	}
	if result.Size != model.Size {
		t.Errorf("Expected Size %v, got %v", model.Size, result.Size)
	}
}

