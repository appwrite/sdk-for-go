func TestRuntimeLogModel(t *testing.T) {
	model := RuntimeLog{Id: "5e5ea5c16897e", ResourceType: "functions", ResourceId: "610fc2f985ee0", ResourceInternalId: "42", DeploymentId: "610fc2f985ee0", Region: "fra", Timestamp: "2020-10-15T06:38:00.000+00:00", Stream: "stdout", Message: "Listening on port 3000"}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result RuntimeLog
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.ResourceType != model.ResourceType {
		t.Errorf("Expected ResourceType %v, got %v", model.ResourceType, result.ResourceType)
	}
	if result.ResourceId != model.ResourceId {
		t.Errorf("Expected ResourceId %v, got %v", model.ResourceId, result.ResourceId)
	}
	if result.ResourceInternalId != model.ResourceInternalId {
		t.Errorf("Expected ResourceInternalId %v, got %v", model.ResourceInternalId, result.ResourceInternalId)
	}
	if result.DeploymentId != model.DeploymentId {
		t.Errorf("Expected DeploymentId %v, got %v", model.DeploymentId, result.DeploymentId)
	}
	if result.Region != model.Region {
		t.Errorf("Expected Region %v, got %v", model.Region, result.Region)
	}
	if result.Timestamp != model.Timestamp {
		t.Errorf("Expected Timestamp %v, got %v", model.Timestamp, result.Timestamp)
	}
	if result.Stream != model.Stream {
		t.Errorf("Expected Stream %v, got %v", model.Stream, result.Stream)
	}
	if result.Message != model.Message {
		t.Errorf("Expected Message %v, got %v", model.Message, result.Message)
	}
}

