func TestVideoRenditionModel(t *testing.T) {
	model := VideoRendition{Id: "5e5ea5c16897e", CreatedAt: "2020-10-15T06:38:00.000+00:00", UpdatedAt: "2020-10-15T06:38:00.000+00:00", VideoId: "5e5ea5c16897e", ProfileId: "d5fg5ehg1c168g7c", Name: "1280X720@3679", StartedAt: "2020-10-15T06:38:00.000+00:00", EndedAt: "2020-10-15T06:38:00.000+00:00", Width: 1280, Height: 720, VideoBitRate: 3551000, AudioBitRate: 128000, TargetDuration: 6.006, Status: "ready", Error: "The requested file is not a valid video or audio file (ffprobe: Invalid data found when processing input)", Progress: 88, Output: "hls", Codec: "h264", Size: 18350080}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result VideoRendition
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.CreatedAt != model.CreatedAt {
		t.Errorf("Expected CreatedAt %v, got %v", model.CreatedAt, result.CreatedAt)
	}
	if result.UpdatedAt != model.UpdatedAt {
		t.Errorf("Expected UpdatedAt %v, got %v", model.UpdatedAt, result.UpdatedAt)
	}
	if result.VideoId != model.VideoId {
		t.Errorf("Expected VideoId %v, got %v", model.VideoId, result.VideoId)
	}
	if result.ProfileId != model.ProfileId {
		t.Errorf("Expected ProfileId %v, got %v", model.ProfileId, result.ProfileId)
	}
	if result.Name != model.Name {
		t.Errorf("Expected Name %v, got %v", model.Name, result.Name)
	}
	if result.StartedAt != model.StartedAt {
		t.Errorf("Expected StartedAt %v, got %v", model.StartedAt, result.StartedAt)
	}
	if result.EndedAt != model.EndedAt {
		t.Errorf("Expected EndedAt %v, got %v", model.EndedAt, result.EndedAt)
	}
	if result.Width != model.Width {
		t.Errorf("Expected Width %v, got %v", model.Width, result.Width)
	}
	if result.Height != model.Height {
		t.Errorf("Expected Height %v, got %v", model.Height, result.Height)
	}
	if result.VideoBitRate != model.VideoBitRate {
		t.Errorf("Expected VideoBitRate %v, got %v", model.VideoBitRate, result.VideoBitRate)
	}
	if result.AudioBitRate != model.AudioBitRate {
		t.Errorf("Expected AudioBitRate %v, got %v", model.AudioBitRate, result.AudioBitRate)
	}
	if result.TargetDuration != model.TargetDuration {
		t.Errorf("Expected TargetDuration %v, got %v", model.TargetDuration, result.TargetDuration)
	}
	if result.Status != model.Status {
		t.Errorf("Expected Status %v, got %v", model.Status, result.Status)
	}
	if result.Error != model.Error {
		t.Errorf("Expected Error %v, got %v", model.Error, result.Error)
	}
	if result.Progress != model.Progress {
		t.Errorf("Expected Progress %v, got %v", model.Progress, result.Progress)
	}
	if result.Output != model.Output {
		t.Errorf("Expected Output %v, got %v", model.Output, result.Output)
	}
	if result.Codec != model.Codec {
		t.Errorf("Expected Codec %v, got %v", model.Codec, result.Codec)
	}
	if result.Size != model.Size {
		t.Errorf("Expected Size %v, got %v", model.Size, result.Size)
	}
}

