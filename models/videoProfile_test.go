package models

import (
	"encoding/json"
	"reflect"
	"testing"
)

func TestVideoProfileModel(t *testing.T) {
	model := VideoProfile{Id: "5e5ea5c16897e", CreatedAt: "2020-10-15T06:38:00.000+00:00", UpdatedAt: "2020-10-15T06:38:00.000+00:00", Name: "360p", Codec: "h264", VideoBitRate: 890000, AudioBitRate: 64000, Width: 640, Height: 360}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result VideoProfile
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.CreatedAt != model.CreatedAt {
		t.Errorf("Expected CreatedAt %v, got %v", model.CreatedAt, result.CreatedAt)
	}
	if result.UpdatedAt != model.UpdatedAt {
		t.Errorf("Expected UpdatedAt %v, got %v", model.UpdatedAt, result.UpdatedAt)
	}
	if result.Name != model.Name {
		t.Errorf("Expected Name %v, got %v", model.Name, result.Name)
	}
	if result.Codec != model.Codec {
		t.Errorf("Expected Codec %v, got %v", model.Codec, result.Codec)
	}
	if result.VideoBitRate != model.VideoBitRate {
		t.Errorf("Expected VideoBitRate %v, got %v", model.VideoBitRate, result.VideoBitRate)
	}
	if result.AudioBitRate != model.AudioBitRate {
		t.Errorf("Expected AudioBitRate %v, got %v", model.AudioBitRate, result.AudioBitRate)
	}
	if result.Width != model.Width {
		t.Errorf("Expected Width %v, got %v", model.Width, result.Width)
	}
	if result.Height != model.Height {
		t.Errorf("Expected Height %v, got %v", model.Height, result.Height)
	}
}

