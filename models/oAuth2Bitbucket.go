package models

import (
	"encoding/json"
	"errors"
)

// OAuth2Bitbucket Model
type OAuth2Bitbucket struct {
	// OAuth2 provider ID.
	Id string `json:"$id"`
	// OAuth2 provider is active and can be used to create sessions.
	Enabled bool `json:"enabled"`
	// Bitbucket OAuth2 key.
	Key string `json:"key"`
	// Bitbucket OAuth2 secret.
	Secret string `json:"secret"`

	// Used by Decode() method
	data []byte
}

func (model OAuth2Bitbucket) New(data []byte) *OAuth2Bitbucket {
	model.data = data
	return &model
}

// UnmarshalJSON decodes a response into a fresh model: present keys keep their
// value, and required keys the response omits take their documented default.
func (model *OAuth2Bitbucket) UnmarshalJSON(data []byte) error {
	type alias OAuth2Bitbucket
	decoded := alias{data: model.data}
	if err := json.Unmarshal(data, &decoded); err != nil {
		return err
	}

	var present struct {
		Id      json.RawMessage `json:"$id"`
		Enabled json.RawMessage `json:"enabled"`
		Key     json.RawMessage `json:"key"`
		Secret  json.RawMessage `json:"secret"`
	}
	if err := json.Unmarshal(data, &present); err != nil {
		return err
	}
	if present.Id == nil {
		if err := json.Unmarshal([]byte("\"\""), &decoded.Id); err != nil {
			return err
		}
	}
	if present.Enabled == nil {
		if err := json.Unmarshal([]byte("false"), &decoded.Enabled); err != nil {
			return err
		}
	}
	if present.Key == nil {
		if err := json.Unmarshal([]byte("\"\""), &decoded.Key); err != nil {
			return err
		}
	}
	if present.Secret == nil {
		if err := json.Unmarshal([]byte("\"\""), &decoded.Secret); err != nil {
			return err
		}
	}

	*model = OAuth2Bitbucket(decoded)
	return nil
}

func (model *OAuth2Bitbucket) Decode(value interface{}) error {
	if len(model.data) <= 0 {
		return errors.New("method Decode() cannot be used on nested struct")
	}

	err := json.Unmarshal(model.data, value)
	if err != nil {
		return err
	}

	return nil
}
