func TestAnalyticsAnnotationModel(t *testing.T) {
	model := AnalyticsAnnotation{Id: "5e5ea5c16897e", CreatedAt: "2020-10-15T06:38:00.000+00:00", UpdatedAt: "2020-10-15T06:38:00.000+00:00", PropertyId: "5e5ea5c16897e", Date: "2020-10-15T06:38:00.000+00:00", Content: "Launched the new pricing page", UserId: "5e5ea5c16897e"}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result AnalyticsAnnotation
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.CreatedAt != model.CreatedAt {
		t.Errorf("Expected CreatedAt %v, got %v", model.CreatedAt, result.CreatedAt)
	}
	if result.UpdatedAt != model.UpdatedAt {
		t.Errorf("Expected UpdatedAt %v, got %v", model.UpdatedAt, result.UpdatedAt)
	}
	if result.PropertyId != model.PropertyId {
		t.Errorf("Expected PropertyId %v, got %v", model.PropertyId, result.PropertyId)
	}
	if result.Date != model.Date {
		t.Errorf("Expected Date %v, got %v", model.Date, result.Date)
	}
	if result.Content != model.Content {
		t.Errorf("Expected Content %v, got %v", model.Content, result.Content)
	}
	if result.UserId != model.UserId {
		t.Errorf("Expected UserId %v, got %v", model.UserId, result.UserId)
	}
}

