func TestProxyRuleRecordModel(t *testing.T) {
	model := ProxyRuleRecord{Id: "5e5ea5c16897e", CreatedAt: "2020-10-15T06:38:00.000+00:00", UpdatedAt: "2020-10-15T06:38:00.000+00:00", Type: "CNAME", Name: "appwrite.company.com", Expected: "appwrite.network", Current: []string{"test"}, Status: "verified", Message: "string", Required: true}

	data, err := json.Marshal(model)
	if err != nil {
		t.Fatal(err)
	}

	var result ProxyRuleRecord
	err = json.Unmarshal(data, &result)
	if err != nil {
		t.Fatal(err)
	}
	if result.Id != model.Id {
		t.Errorf("Expected Id %v, got %v", model.Id, result.Id)
	}
	if result.CreatedAt != model.CreatedAt {
		t.Errorf("Expected CreatedAt %v, got %v", model.CreatedAt, result.CreatedAt)
	}
	if result.UpdatedAt != model.UpdatedAt {
		t.Errorf("Expected UpdatedAt %v, got %v", model.UpdatedAt, result.UpdatedAt)
	}
	if result.Type != model.Type {
		t.Errorf("Expected Type %v, got %v", model.Type, result.Type)
	}
	if result.Name != model.Name {
		t.Errorf("Expected Name %v, got %v", model.Name, result.Name)
	}
	if result.Expected != model.Expected {
		t.Errorf("Expected Expected %v, got %v", model.Expected, result.Expected)
	}
	if result.Status != model.Status {
		t.Errorf("Expected Status %v, got %v", model.Status, result.Status)
	}
	if result.Message != model.Message {
		t.Errorf("Expected Message %v, got %v", model.Message, result.Message)
	}
	if result.Required != model.Required {
		t.Errorf("Expected Required %v, got %v", model.Required, result.Required)
	}
}

